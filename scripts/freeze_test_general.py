"""Freeze test-general: the LinTO test split at a pinned revision (D-12, D-13, D-14).

Writes configs/data/test-general.yaml. Run it once; rerunning must reproduce the file
byte for byte. Usage: uv run python scripts/freeze_test_general.py
"""

import argparse
import hashlib
from collections import Counter
from pathlib import Path

import yaml
from huggingface_hub import HfApi

from tuncall.data.testsets import (
    Manifest,
    ParquetFile,
    fetch,
    iter_rows,
    segment_digest,
    sha256_file,
)

REPO = "linagora/linto-dataset-audio-ar-tn"
REVISION = "99796bfd5e8b48febaac60633d1ec97a658fa511"
OUT = Path(__file__).resolve().parents[1] / "configs" / "data" / "test-general.yaml"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, default=OUT)
    args = parser.parse_args()

    paths = sorted(
        p
        for p in HfApi().list_repo_files(REPO, repo_type="dataset", revision=REVISION)
        if p.startswith("data/") and "/test/" in p and p.endswith(".parquet")
    )
    draft = Manifest(
        name="test-general",
        repo=REPO,
        revision=REVISION,
        files=[ParquetFile(path=p, sha256="") for p in paths],
        utterances=0,
        hours=0.0,
        digest="",
    )
    files = fetch(draft)

    segments = []
    audio_hashes: Counter[str] = Counter()
    for segs, encoded in iter_rows(files):
        segments += segs
        audio_hashes[hashlib.sha256(encoded).hexdigest()] += 1

    seconds = sum(s.end - s.start for s in segments)
    manifest = draft.model_copy(
        update={
            "files": [ParquetFile(path=p, sha256=sha256_file(files[p])) for p in paths],
            "utterances": len(segments),
            "hours": round(seconds / 3600, 4),
            "digest": segment_digest(segments),
        }
    )

    long = [s.id for s in segments if s.end - s.start > 30]
    dup_text = sum(n - 1 for n in Counter(s.text for s in segments).values() if n > 1)
    dup_audio = sum(n - 1 for n in audio_hashes.values() if n > 1)
    print(f"{manifest.utterances} utterances, {manifest.hours} h from {len(paths)} files")
    print(
        f"segments > 30 s: {len(long)}  duplicate transcripts: {dup_text}  "
        f"duplicate recordings: {dup_audio}"
    )

    args.out.parent.mkdir(parents=True, exist_ok=True)
    header = "# Generated by scripts/freeze_test_general.py. Do not edit (D-14).\n"
    body = yaml.safe_dump(manifest.model_dump(mode="json"), sort_keys=False, allow_unicode=True)
    args.out.write_text(header + body, encoding="utf-8")
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
