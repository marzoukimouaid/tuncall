"""Choose the LinTO train clips held out as dev (D-17a); writes ``configs/data/dev-linto.txt``.

LinTO has no validation split. Clips are held out by whole recording (``<subset>/<file>`` in
the clip id), so no recording is in both train and dev. Recordings are taken in sha256 order
of their name, skipping any that would push the total past ``--clips``. Reads the D-16b export
only (no audio).

    uv run python scripts/linto_dev_holdout.py --export outputs/sources/linto-train.jsonl
"""

import argparse
import hashlib
import json
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def holdout(ids: list[str], clips: int) -> list[str]:
    """Clip ids of whole recordings, in sha256 order, totalling at most ``clips``."""
    by_recording: dict[str, list[str]] = defaultdict(list)
    for cid in ids:
        by_recording["/".join(cid.split("/")[2:4])].append(cid)
    # shortcut: not stratified by subset, so one long recording can be a big share of dev;
    # stratify if dev WER and test-general WER rank checkpoints differently.
    chosen: list[str] = []
    for rec in sorted(by_recording, key=lambda r: hashlib.sha256(r.encode()).hexdigest()):
        if len(chosen) + len(by_recording[rec]) <= clips:
            chosen += by_recording[rec]
        if len(chosen) == clips:
            break
    return sorted(chosen)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--export", type=Path, default=Path("outputs/sources/linto-train.jsonl"))
    parser.add_argument("--clips", type=int, default=500)
    parser.add_argument("--out", type=Path, default=ROOT / "configs/data/dev-linto.txt")
    args = parser.parse_args()
    with args.export.open(encoding="utf-8") as f:
        ids = [json.loads(line)["id"] for line in f]
    chosen = holdout(ids, args.clips)
    header = "# LinTO train clips held out as dev, never trained on (D-17a).\n"
    header += "# Generated by scripts/linto_dev_holdout.py; do not edit.\n"
    args.out.write_text(header + "".join(f"{c}\n" for c in chosen), encoding="utf-8")
    print(
        f"{len(chosen)} clips from {len({'/'.join(c.split('/')[2:4]) for c in chosen})} "
        f"recordings -> {args.out}"
    )


if __name__ == "__main__":
    main()
