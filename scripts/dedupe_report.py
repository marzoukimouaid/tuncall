"""Dedupe report: text overlap between sources and against both frozen test sets (D-16, #38).

Reads the text export of ``source_stats.py``. Each ``<source>-<split>`` file is one set;
linto-test is test-general and slurp_tn-test is test-domain. A text is transliterated
with the lexicon (D-10a), normalized with ``normalize_arabic`` and counted only if it has
at least 4 words (the D-12b rule, so short common replies don't match by chance).

Cell (row A, column B) = eligible utterances of A whose text also appears in B; on the
diagonal, those whose text appears more than once in A. Writes docs/data/dedupe.md and the
matching ids to outputs/dedupe/matches.jsonl (for filtering training data in Phase 3).

    uv run python scripts/dedupe_report.py [--exports outputs/sources]
"""

import argparse
import hashlib
import json
from collections import Counter, defaultdict
from pathlib import Path

from latin_words import LEXICON
from source_stats import OUT, ROOT, read_export

from tuncall.data.lexicon import load_lexicon, transliterate
from tuncall.eval.normalize import normalize_arabic

MIN_WORDS = 4
REPORT = ROOT / "docs" / "data" / "dedupe.md"
MATCHES = ROOT / "outputs" / "dedupe" / "matches.jsonl"

type Matrix = dict[str, dict[str, int]]


def overlap(
    sets: dict[str, list[tuple[str, str]]], lexicon: dict[str, str]
) -> tuple[dict[str, int], Matrix, dict[str, list[str]]]:
    """Eligible counts, the overlap matrix, and for each matching id the other sets it's in."""
    keys = {
        name: [(i, normalize_arabic(transliterate(t, lexicon))) for i, t in rows]
        for name, rows in sets.items()
    }
    keys = {
        name: [(i, k) for i, k in rows if len(k.split()) >= MIN_WORDS]
        for name, rows in keys.items()
    }
    counts = {name: Counter(k for _, k in rows) for name, rows in keys.items()}
    matrix: Matrix = {}
    matches: dict[str, list[str]] = defaultdict(list)
    for a, rows in keys.items():
        matrix[a] = {}
        for b in keys:
            if a == b:
                matrix[a][b] = sum(counts[a][k] > 1 for _, k in rows)
                continue
            hits = [i for i, k in rows if k in counts[b]]
            matrix[a][b] = len(hits)
            for i in hits:
                matches[i].append(b)
    return {name: len(rows) for name, rows in keys.items()}, matrix, dict(matches)


def render(eligible: dict[str, int], matrix: Matrix) -> str:
    names = list(matrix)
    lines = [
        "| set | eligible | " + " | ".join(names) + " |",
        "|---|---:|" + "---:|" * len(names),
    ]
    for a in names:
        cells = " | ".join(str(matrix[a][b]) for b in names)
        lines.append(f"| {a} | {eligible[a]} | {cells} |")
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--exports", type=Path, default=OUT)
    parser.add_argument("--lexicon", type=Path, default=LEXICON)
    args = parser.parse_args()

    sets: dict[str, list[tuple[str, str]]] = defaultdict(list)
    for name, row in read_export(args.exports):
        sets[name].append((row["id"], row["text"]))
    if args.lexicon.exists():
        lexicon = load_lexicon(args.lexicon)
        lexicon_id = hashlib.sha256(args.lexicon.read_bytes()).hexdigest()
    else:
        lexicon, lexicon_id = {}, "none (texts not transliterated)"
    eligible, matrix, matches = overlap(dict(sets), lexicon)

    table = render(eligible, matrix)
    REPORT.parent.mkdir(parents=True, exist_ok=True)
    REPORT.write_text(
        "# Dedupe report (D-16)\n\n"
        "Generated by `scripts/dedupe_report.py` from the `scripts/source_stats.py` export "
        "of `configs/data/train-mix.yaml`. Do not edit.\n\n"
        f"- Lexicon sha256: {lexicon_id}\n"
        f"- Eligible: normalized text with at least {MIN_WORDS} words (D-12b rule)\n"
        "- Cell (row A, column B): eligible utterances of A whose text also appears in B; "
        "diagonal: texts repeated within A\n"
        "- test-general = linto-test, test-domain = slurp_tn-test\n\n"
        f"{table}\n",
        encoding="utf-8",
    )
    MATCHES.parent.mkdir(parents=True, exist_ok=True)
    with MATCHES.open("w", encoding="utf-8") as f:
        for i, names in matches.items():
            f.write(json.dumps({"id": i, "sets": names}) + "\n")
    print(table)
    print(f"{len(matches)} matching utterances -> {MATCHES}; report -> {REPORT}")


if __name__ == "__main__":
    main()
