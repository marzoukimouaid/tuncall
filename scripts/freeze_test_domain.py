"""Freeze test-domain: the SLURP-TN test split at a pinned revision (D-13a, D-14b).

References are SLURP-TN's ``tun_transcription``, transliterated with the D-10a lexicon,
whose sha256 is pinned too. Writes configs/data/test-domain.yaml; rerunning must reproduce
it byte for byte. Usage: uv run python scripts/freeze_test_domain.py
"""

import argparse
import io
from collections import Counter
from pathlib import Path

import soundfile as sf
import yaml
from huggingface_hub import HfApi

from tuncall.data.lexicon import latin_words
from tuncall.data.testsets import (
    LexiconRef,
    Manifest,
    ParquetFile,
    fetch,
    iter_cuts,
    segment_digest,
    sha256_file,
)

REPO = "Elyadata/SLURP-TN"
REVISION = "a5c2ec062fa91b5a51b7c914859eb1e6525a6f5d"  # same as train-mix.yaml (D-16a)
ROOT = Path(__file__).resolve().parents[1]
LEXICON = "configs/data/lexicon.tsv"
OUT = ROOT / "configs" / "data" / "test-domain.yaml"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, default=OUT)
    args = parser.parse_args()

    paths = sorted(
        p
        for p in HfApi().list_repo_files(REPO, repo_type="dataset", revision=REVISION)
        if p.startswith("data/test-") and p.endswith(".parquet")
    )
    draft = Manifest(
        name="test-domain",
        repo=REPO,
        revision=REVISION,
        files=[ParquetFile(path=p, sha256="") for p in paths],
        utterances=0,
        hours=0.0,
        digest="",
        layout="clips",
        text_column="tun_transcription",
        lexicon=LexiconRef(path=LEXICON, sha256=sha256_file(ROOT / LEXICON)),
    )
    files = fetch(draft)

    segments = []
    seconds = 0.0
    for segs, encoded in iter_cuts(draft, files):
        info = sf.info(io.BytesIO(encoded))
        seconds += info.frames / info.samplerate
        segments += segs

    manifest = draft.model_copy(
        update={
            "files": [ParquetFile(path=p, sha256=sha256_file(files[p])) for p in paths],
            "utterances": len(segments),
            "hours": round(seconds / 3600, 4),
            "digest": segment_digest(segments),
        }
    )

    ids = Counter(s.id for s in segments)
    latin = sum(len(latin_words(s.text)) for s in segments)
    print(f"{manifest.utterances} utterances, {manifest.hours} h from {len(paths)} files")
    print(f"duplicate ids: {sum(n - 1 for n in ids.values())}  Latin tokens left: {latin}")
    if len(ids) != len(segments):
        raise SystemExit("utterance ids are not unique")

    args.out.parent.mkdir(parents=True, exist_ok=True)
    header = "# Generated by scripts/freeze_test_domain.py. Do not edit (D-14b).\n"
    body = yaml.safe_dump(manifest.model_dump(mode="json"), sort_keys=False, allow_unicode=True)
    args.out.write_text(header + body, encoding="utf-8")
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
