"""Freeze a simulated conversation set from TEDxTN (D-13b, ADR 0008).

``--set dev`` builds from TEDxTN validation, ``--set test`` from TEDxTN test. Writes
configs/data/conversations-<set>.tsv (the placed clips) and conversations-<set>.yaml
(pinned revision, lexicon and hashes); rerunning must reproduce both byte for byte.
Usage: uv run python scripts/build_conversations.py --set test
"""

import argparse
from collections import Counter
from pathlib import Path

import yaml

from tuncall.config import load_config
from tuncall.data.conversations import (
    ConversationSet,
    assemble,
    audio_digest,
    load_conversations,
    parse,
    plan,
    split_audio,
    write_turns,
)
from tuncall.data.lexicon import load_lexicon
from tuncall.data.sources import TrainMix
from tuncall.data.testsets import REPO_ROOT, SAMPLE_RATE, LexiconRef, sha256_file

SPLITS = {"dev": "validation", "test": "test"}
SEED = 0
LEXICON = "configs/data/lexicon.tsv"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--set", choices=SPLITS, required=True)
    args = parser.parse_args()

    mix = load_config(REPO_ROOT / "configs/data/train-mix.yaml", TrainMix)
    revision = next(s.revision for s in mix.sources if s.source == "tedxtn")  # D-16a
    split = SPLITS[args.set]
    name = f"conversations-{args.set}"
    tsv = Path("configs/data") / f"{name}.tsv"

    audio, text = split_audio(split, revision, load_lexicon(REPO_ROOT / LEXICON))
    placed = plan({k: len(a) / SAMPLE_RATE for k, a in audio.items()}, SEED, args.set)
    write_turns(REPO_ROOT / tsv, placed)
    conversations = assemble(placed, audio, text)

    seconds = sum(len(c.audio) for c in conversations) / SAMPLE_RATE
    manifest = ConversationSet(
        name=name,
        repo="Hediske/tedxtn-tunisian-segmented",
        revision=revision,
        split=split,
        seed=SEED,
        turns=str(tsv),
        turns_sha256=sha256_file(REPO_ROOT / tsv),
        audio_sha256=audio_digest(conversations),
        lexicon=LexiconRef(path=LEXICON, sha256=sha256_file(REPO_ROOT / LEXICON)),
        conversations=len(conversations),
        hours=round(seconds / 3600, 4),
    )
    out = REPO_ROOT / "configs/data" / f"{name}.yaml"
    header = "# Generated by scripts/build_conversations.py. Do not edit (D-13b).\n"
    out.write_text(header + yaml.safe_dump(manifest.model_dump(mode="json"), sort_keys=False))

    pairs = Counter(
        frozenset(parse(p.clip)[0] for p in placed if p.conversation == c.id) for c in conversations
    )
    lengths = sorted(len(c.audio) / SAMPLE_RATE for c in conversations)
    turns = sum(len(c.turns) for c in conversations)
    overlaps = sum(
        b.start < a.end for c in conversations for a, b in zip(c.turns, c.turns[1:], strict=False)
    )
    print(
        f"{name}: {len(conversations)} conversations, {manifest.hours} h, "
        f"length {lengths[0]:.0f}-{lengths[-1]:.0f} s, {turns} turns, "
        f"{overlaps} overlapping turn changes, {len(pairs)} talk pairs, "
        f"{len(placed)}/{len(audio)} clips used"
    )
    load_conversations(manifest)  # rebuild from the frozen files as a self-check
    print(f"wrote {tsv} and {out.relative_to(REPO_ROOT)}")


if __name__ == "__main__":
    main()
